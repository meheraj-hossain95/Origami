FILLED = frozenset({"play", "pause", "dot"})


@lru_cache(maxsize=512)
def _render(name: str, color: str, size: int, dpr: float) -> QPixmap:
    fill = color if name in FILLED else "none"
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="{fill}" stroke="{color}" '
        f'stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">{PATHS[name]}</svg>'
    )
    px = QPixmap(round(size * dpr), round(size * dpr))
    px.setDevicePixelRatio(dpr)
    px.fill(Qt.GlobalColor.transparent)
    painter = QPainter(px)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    QSvgRenderer(QByteArray(svg.encode())).render(painter, QRectF(0, 0, size, size))
    painter.end()
    return px


def pixmap(name: str, color: str, size: int = 18) -> QPixmap:
    screen = QGuiApplication.primaryScreen()
    return _render(name, color, size, screen.devicePixelRatio() if screen else 1.0)


def icon(name: str, color: str, size: int = 18, pad: int = 0) -> QIcon:
    px = pixmap(name, color, size)
    if not pad:
        return QIcon(px)
    dpr = px.devicePixelRatio()
    canvas = QPixmap(round((size + pad) * dpr), round(size * dpr))
    canvas.setDevicePixelRatio(dpr)
    canvas.fill(Qt.GlobalColor.transparent)
    painter = QPainter(canvas)
    painter.drawPixmap(0, 0, px)
    painter.end()
    return QIcon(canvas)
